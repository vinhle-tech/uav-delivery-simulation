export type User = {id:string;email:string;fullName:string;role:'ADMIN'|'OPERATOR'};
export type Session = {user:User;accessToken:string;refreshToken:string;expiresIn:number};
export type AuthState = {session:Session|null;busy:boolean;notice:string};
export const BASE='http://127.0.0.1:3000';
export function errorMessage(body:unknown):string {
  if(body && typeof body==='object' && 'error' in body){
    const e=body.error;
    if(typeof e==='string')return e;
    if(e && typeof e==='object' && 'message' in e && typeof e.message==='string')return e.message;
  }
  return 'Yêu cầu không thành công.';
}
function parseSession(body:unknown):Session {
  const s=body as Session;
  if(!s||typeof s.accessToken!=='string'||!s.accessToken||typeof s.refreshToken!=='string'||!s.refreshToken||!s.user||!['ADMIN','OPERATOR'].includes(s.user.role)||typeof s.user.id!=='string'||typeof s.user.email!=='string'||typeof s.user.fullName!=='string'||!Number.isFinite(s.expiresIn)||s.expiresIn<=0)throw Error('Phản hồi xác thực không hợp lệ.');
  return s;
}
export function createAuthClient(request:typeof fetch=(...args)=>fetch(...args)) {
  let state:AuthState={session:null,busy:false,notice:''};
  let epoch=0, expiresAt=0;
  let pending:Promise<Session>|null=null;
  const listeners=new Set<()=>void>();
  const set=(next:Partial<AuthState>)=>{state={...state,...next};listeners.forEach(fn=>fn());};
  const clear=(notice:string)=>{epoch++;expiresAt=0;set({session:null,busy:false,notice});};
  async function post(path:string,body:object){
    return request(BASE+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body),cache:'no-store',redirect:'error',signal:AbortSignal.timeout(10000)});
  }
  async function login(email:string,password:string){
    if(state.busy||state.session)throw Error('Đang có phiên hoặc yêu cầu xác thực.');
    set({busy:true,notice:''});
    try{const r=await post('/api/auth/login',{email,password});const b=await r.json();if(!r.ok)throw Error(errorMessage(b));const s=parseSession(b);epoch++;expiresAt=Date.now()+s.expiresIn*1000;set({session:s});}
    finally{set({busy:false});}
  }
  function refresh():Promise<Session>{
    if(pending)return pending;
    const s=state.session, gen=epoch;
    if(!s||state.busy)return Promise.reject(Error('Cần đăng nhập.'));
    const operation=(async()=>{
      const r=await post('/api/auth/refresh',{refreshToken:s.refreshToken});
      if(!r.ok){if((r.status===400||r.status===401)&&epoch===gen)clear('Phiên đã hết hạn hoặc bị thu hồi. Vui lòng đăng nhập lại.');throw Error('Không thể làm mới phiên.');}
      const next=parseSession(await r.json());
      if(epoch!==gen)throw Error('Phiên đã thay đổi.');
      expiresAt=Date.now()+next.expiresIn*1000;set({session:next});return next;
    })();
    pending=operation.finally(()=>{pending=null;});return pending;
  }
  async function authFetch(url:string,init:RequestInit={}):Promise<Response>{
    const target=new URL(url,BASE);
    if(target.origin!==BASE||!target.pathname.startsWith('/api/')||target.pathname.startsWith('/api/auth/'))throw Error('Địa chỉ API không hợp lệ.');
    let s=state.session;const gen=epoch;
    if(!s||state.busy)throw Error('Cần đăng nhập.');
    if(Date.now()>=expiresAt-30000)s=await refresh();
    const send=(token:string)=>{
      if(epoch!==gen||state.busy||!state.session)throw Error('Phiên đã thay đổi.');
      const headers=new Headers(init.headers);headers.set('Authorization','Bearer '+token);
      return request(target.href,{...init,headers,redirect:'error',cache:'no-store'});
    };
    let r=await send(s.accessToken);
    if(r.status!==401)return r;
    if(epoch!==gen||!state.session||state.busy)throw Error('Phiên đã thay đổi.');
    // A 401 is generated by the auth gate before command execution. Never retry on network errors or 403/5xx.
    const next=state.session.accessToken!==s.accessToken?state.session:await refresh();
    r=await send(next.accessToken);
    if(r.status===401&&epoch===gen&&state.session?.accessToken===next.accessToken)clear('Phiên không còn hợp lệ. Vui lòng đăng nhập lại.');
    return r;
  }
  async function logout(){
    if(state.busy||!state.session)return;
    set({busy:true,notice:''});
    try{
      // Wait for any rotation before revoking the most recent token.
      if(pending)try{await pending;}catch{/* session may already be invalid */}
      const s=state.session;if(!s)return;
      const r=await post('/api/auth/logout',{refreshToken:s.refreshToken});
      if(!r.ok)throw Error('Backend chưa xác nhận đăng xuất. Hãy thử lại.');
      clear('Đã đăng xuất.');
    }catch(e){set({notice:'Chưa xác nhận đăng xuất với Backend. Kiểm tra kết nối và thử lại.'});throw e;}
    finally{set({busy:false});}
  }
  return {login,logout,authFetch,refresh,subscribe:(fn:()=>void)=>{listeners.add(fn);return ()=>{listeners.delete(fn);};},getSnapshot:()=>state};
}
export const authClient=createAuthClient();
export const authFetch=authClient.authFetch;
